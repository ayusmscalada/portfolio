/**
 * Generates src/components/ph.jsx: a tiny subset of Phosphor icons (MIT,
 * https://phosphoricons.com) containing only the weights this site uses.
 * Shipping the full package costs every icon all six weights.
 *
 *   node scripts/gen-icons.mjs
 *
 * Add an icon name (and the weights you need) to ICONS, then re-run.
 */
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const ICONS = {
  ArrowDown: ['regular'],
  ArrowUp: ['bold'],
  ArrowUpRight: ['bold'],
  CaretDown: ['bold'],
  Cloud: ['regular'],
  Code: ['regular'],
  Compass: ['regular'],
  Copy: ['regular'],
  Cpu: ['regular'],
  Database: ['regular'],
  EnvelopeSimple: ['regular', 'fill'],
  GitBranch: ['regular', 'fill'],
  GithubLogo: ['regular', 'bold'],
  House: ['regular', 'fill'],
  LinkedinLogo: ['regular'],
  List: ['regular'],
  LockSimple: ['bold'],
  Moon: ['regular'],
  PenNib: ['regular'],
  Pause: ['fill'],
  Play: ['fill'],
  Sparkle: ['regular', 'fill'],
  SquaresFour: ['regular', 'fill'],
  Sun: ['regular'],
  User: ['regular', 'fill'],
  XLogo: ['regular'],
}

const require = createRequire(import.meta.url)
const React = require('react')
const root = new URL('../node_modules/@phosphor-icons/react/dist/defs/', import.meta.url)

const toNodes = (el) => {
  const kids = React.Children.toArray(el.props.children)
  return kids.map((k) => {
    const { children, ...props } = k.props
    return [k.type, props]
  })
}

const data = {}
for (const [name, weights] of Object.entries(ICONS)) {
  const mod = await import(new URL(`${name}.es.js`, root))
  const map = mod.default
  data[name] = Object.fromEntries(weights.map((w) => [w, toNodes(map.get(w))]))
}

const out = `/* eslint-disable */
// GENERATED by scripts/gen-icons.mjs from @phosphor-icons/react (MIT). Do not edit by hand.
import { createElement as h, forwardRef } from 'react'

const DATA = ${JSON.stringify(data)}

function make(name) {
  const weights = DATA[name]
  const Icon = forwardRef(function Icon({ size = 24, weight = 'regular', color = 'currentColor', ...rest }, ref) {
    const nodes = weights[weight] || weights.regular || Object.values(weights)[0]
    return h(
      'svg',
      { ref, xmlns: 'http://www.w3.org/2000/svg', width: size, height: size, viewBox: '0 0 256 256', fill: color, ...rest },
      nodes.map(([type, props], i) => h(type, { key: i, ...props })),
    )
  })
  Icon.displayName = name
  return Icon
}

${Object.keys(ICONS).map((n) => `export const ${n} = make('${n}')`).join('\n')}
`
writeFileSync(new URL('../src/components/ph.jsx', import.meta.url), out)
console.log('wrote', out.length, 'bytes for', Object.keys(ICONS).length, 'icons')
